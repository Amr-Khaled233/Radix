/**
 * Generates theme-aware brand assets from the supplied SVGs in public/brand.
 *
 * The only transformation applied to the logo artwork is replacing the single
 * fill colour with `currentColor`. Path geometry is copied byte-for-byte.
 * Originals are never modified.
 *
 * Outputs:
 *   public/brand/current/*.svg            currentColor copies of the four lockups
 *   components/brand/generated/logos.ts   viewBox + path markup for <Logo />
 *   components/brand/generated/icons.ts   viewBox + inner markup for <Icon />
 *   app/favicon.ico, app/icon.svg, app/apple-icon.png, public/icons/*.png
 *
 * Run: pnpm brand:generate
 */
import { mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

const ROOT = process.cwd();
const BRAND_DIR = path.join(ROOT, "public/brand");
const GENERATED_DIR = path.join(ROOT, "components/brand/generated");

const AUBERGINE = "#1B1028";
const IVORY = "#F6F3EE";

const LOGOS = {
  horizontal: "hor.svg",
  vertical: "ver.svg",
  wordmark: "typo.svg",
  icon: "icon.svg",
} as const;

const HEADER = "// Generated by scripts/generate-brand-assets.ts — do not edit.\n";

function viewBoxOf(svg: string, file: string) {
  const match = svg.match(/viewBox="([^"]+)"/);
  if (!match) throw new Error(`${file}: missing viewBox`);
  return match[1];
}

/** Returns the markup inside the single `<g fill="#1B1028">` group of a logo file. */
function logoPaths(svg: string, file: string) {
  const groups = svg.match(/<g fill="#1B1028">([\s\S]*?)<\/g>/g) ?? [];
  if (groups.length !== 1) throw new Error(`${file}: expected exactly one fill group`);
  const inner = groups[0].replace(/^<g fill="#1B1028">/, "").replace(/<\/g>$/, "");
  if (/fill="/.test(inner)) throw new Error(`${file}: unexpected nested fill`);
  return inner.trim().replace(/\s*\n\s*/g, "");
}

async function generateLogos() {
  await mkdir(path.join(BRAND_DIR, "current"), { recursive: true });
  const entries: string[] = [];
  const artwork: Record<string, { viewBox: string; paths: string }> = {};

  for (const [variant, file] of Object.entries(LOGOS)) {
    const svg = await readFile(path.join(BRAND_DIR, file), "utf8");
    const viewBox = viewBoxOf(svg, file);
    const paths = logoPaths(svg, file);
    artwork[variant] = { viewBox, paths };

    await writeFile(
      path.join(BRAND_DIR, "current", file),
      svg.replace('<g fill="#1B1028">', '<g fill="currentColor">'),
    );
    entries.push(`  ${variant}: { viewBox: ${JSON.stringify(viewBox)}, paths: ${JSON.stringify(paths)} },`);
  }

  await writeFile(
    path.join(GENERATED_DIR, "logos.ts"),
    `${HEADER}\nexport const logoArtwork = {\n${entries.join("\n")}\n} as const;\n\nexport type LogoVariant = keyof typeof logoArtwork;\n`,
  );
  return artwork;
}

async function generateIcons() {
  const dir = path.join(BRAND_DIR, "icons");
  const files = (await readdir(dir)).filter((f) => f.endsWith(".svg")).sort();
  const entries: string[] = [];

  for (const file of files) {
    const svg = await readFile(path.join(dir, file), "utf8");
    const viewBox = viewBoxOf(svg, file);
    const inner = svg
      .replace(/^[\s\S]*?<svg[^>]*>/, "")
      .replace(/<\/svg>\s*$/, "")
      .trim()
      .replace(/\s*\n\s*/g, "");
    const name = file.replace(/\.svg$/, "");
    entries.push(
      `  ${JSON.stringify(name)}: { viewBox: ${JSON.stringify(viewBox)}, inner: ${JSON.stringify(inner)} },`,
    );
  }

  await writeFile(
    path.join(GENERATED_DIR, "icons.ts"),
    `${HEADER}\nexport const iconArtwork = {\n${entries.join("\n")}\n} as const;\n\nexport type IconName = keyof typeof iconArtwork;\n`,
  );
  return files.length;
}

/** Ivory icon on an Aubergine square, with the icon's 25%-of-width clear space on every side. */
function appIconSvg({ viewBox, paths }: { viewBox: string; paths: string }) {
  const [, , w, h] = viewBox.split(/\s+/).map(Number);
  const pad = w * 0.25;
  const size = Math.max(w, h) + pad * 2;
  const x = (size - w) / 2;
  const y = (size - h) / 2;
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${size} ${size}"><rect width="${size}" height="${size}" fill="${AUBERGINE}"/><g transform="translate(${x} ${y})" fill="${IVORY}">${paths}</g></svg>`;
}

/** Minimal ICO container holding PNG images (supported by all current browsers). */
function buildIco(images: { size: number; data: Buffer }[]) {
  const header = Buffer.alloc(6);
  header.writeUInt16LE(0, 0);
  header.writeUInt16LE(1, 2);
  header.writeUInt16LE(images.length, 4);
  const dir = Buffer.alloc(16 * images.length);
  let offset = 6 + dir.length;
  images.forEach(({ size, data }, i) => {
    const o = i * 16;
    dir.writeUInt8(size >= 256 ? 0 : size, o);
    dir.writeUInt8(size >= 256 ? 0 : size, o + 1);
    dir.writeUInt8(0, o + 2);
    dir.writeUInt8(0, o + 3);
    dir.writeUInt16LE(1, o + 4);
    dir.writeUInt16LE(32, o + 6);
    dir.writeUInt32LE(data.length, o + 8);
    dir.writeUInt32LE(offset, o + 12);
    offset += data.length;
  });
  return Buffer.concat([header, dir, ...images.map((img) => img.data)]);
}

async function generateAppIcons(icon: { viewBox: string; paths: string }) {
  const svg = appIconSvg(icon);
  const png = (size: number) => sharp(Buffer.from(svg), { density: 1200 }).resize(size, size).png().toBuffer();

  await mkdir(path.join(ROOT, "public/icons"), { recursive: true });
  await writeFile(path.join(ROOT, "app/icon.svg"), svg);
  await writeFile(path.join(ROOT, "app/apple-icon.png"), await png(180));
  for (const size of [192, 512]) {
    await writeFile(path.join(ROOT, `public/icons/icon-${size}.png`), await png(size));
  }
  const ico = await Promise.all([16, 32, 48].map(async (size) => ({ size, data: await png(size) })));
  await writeFile(path.join(ROOT, "app/favicon.ico"), buildIco(ico));
}

async function main() {
  await mkdir(GENERATED_DIR, { recursive: true });
  const artwork = await generateLogos();
  const iconCount = await generateIcons();
  await generateAppIcons(artwork.icon);
  console.log(`Generated 4 logo variants, ${iconCount} icons and app icons.`);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
